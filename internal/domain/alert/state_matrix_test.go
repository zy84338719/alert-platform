package alert

import (
	"testing"
	"time"
)

// PROC-005: every transition path of the docs/03 §4 state diagram, plus the
// out-of-order protections. The matrix below is the acceptance checklist —
// one subtest per edge.

var (
	t0 = time.Date(2026, 11, 14, 10, 0, 0, 0, time.UTC)
	t1 = t0.Add(5 * time.Minute)
	t2 = t1.Add(5 * time.Minute)
)

func obs(ep string, sig Signal, at time.Time) Observation {
	return Observation{EpisodeKey: ep, Signal: sig, OccurredAt: at, ReceivedAt: at.Add(time.Second)}
}

func firing(ep string, at time.Time) Snapshot {
	return Snapshot{EpisodeKey: ep, State: StateFiring, LastObservedAt: at, LastTransitionAt: at, Version: 1}
}

// [*] --> Firing, then the full firing lifecycle.
func TestPathNewFiringToResolved(t *testing.T) {
	out, err := Apply(Snapshot{}, obs("e1", SignalFiring, t0))
	if err != nil || !out.Changed || out.Next.State != StateFiring {
		t.Fatalf("new firing: %+v %v", out, err)
	}
	out, err = Apply(out.Next, obs("e1", SignalResolved, t1))
	if err != nil || !out.Changed || out.Next.State != StateResolved {
		t.Fatalf("firing->resolved: %+v %v", out, err)
	}
	// repeat-resolved is a no-op observation
	out, err = Apply(out.Next, obs("e1", SignalResolved, t2))
	if err != nil || out.Changed {
		t.Fatalf("repeat resolved: %+v %v", out, err)
	}
}

// Pending --> Firing（满足触发阈值）and Pending --> Resolved（异常消失）。
// Pending instances are platform-created (自有持续时长规则); the state machine
// only governs their exits.
func TestPathPendingExits(t *testing.T) {
	pending := Snapshot{EpisodeKey: "e1", State: StatePending, LastObservedAt: t0, LastTransitionAt: t0, Version: 1}
	out, err := Apply(pending, obs("e1", SignalFiring, t1))
	if err != nil || !out.Changed || out.Next.State != StateFiring {
		t.Fatalf("pending->firing: %+v %v", out, err)
	}
	out, err = Apply(pending, obs("e1", SignalResolved, t1))
	if err != nil || !out.Changed || out.Next.State != StateResolved {
		t.Fatalf("pending->resolved: %+v %v", out, err)
	}
}

// Firing --> Stale --> Firing and Firing --> Stale --> Resolved: a stale alert
// is still an open episode; both re-confirmations are legal.
func TestPathStaleReconfirmations(t *testing.T) {
	stale := Snapshot{EpisodeKey: "e1", State: StateStale, LastObservedAt: t1, LastTransitionAt: t1, Version: 2}
	out, err := Apply(stale, obs("e1", SignalFiring, t2))
	if err != nil || !out.Changed || out.Next.State != StateFiring {
		t.Fatalf("stale->firing: %+v %v", out, err)
	}
	out, err = Apply(stale, obs("e1", SignalResolved, t2))
	if err != nil || !out.Changed || out.Next.State != StateResolved {
		t.Fatalf("stale->resolved: %+v %v", out, err)
	}
}

// T-006: a Firing must never reopen an episode closed by a valid recovery —
// an OLDER firing trips the out-of-order guard, a NEWER firing is
// ErrEpisodeClosed (the store opens a NEW episode for the latter).
func TestFiringCannotReopenClosedEpisode(t *testing.T) {
	closed := Snapshot{EpisodeKey: "e1", State: StateResolved, LastObservedAt: t1, LastTransitionAt: t1, Version: 2}
	if _, err := Apply(closed, obs("e1", SignalFiring, t0)); err != ErrOutOfOrder {
		t.Fatalf("older firing on closed episode: err=%v, want ErrOutOfOrder", err)
	}
	if _, err := Apply(closed, obs("e1", SignalFiring, t2)); err != ErrEpisodeClosed {
		t.Fatalf("newer firing on closed episode: err=%v, want ErrEpisodeClosed", err)
	}
}

// Out-of-order protection: an older DIFFERENT state change is rejected; an
// older same-state observation is absorbed as duplicate (docs/03 §6).
func TestOutOfOrderMatrix(t *testing.T) {
	f := firing("e1", t1)
	if _, err := Apply(f, obs("e1", SignalResolved, t0)); err != ErrOutOfOrder {
		t.Fatalf("older resolved vs firing transition: err=%v, want ErrOutOfOrder", err)
	}
	out, err := Apply(f, obs("e1", SignalFiring, t0))
	if err != nil || out.Changed {
		t.Fatalf("older duplicate firing must be absorbed: %+v %v", out, err)
	}
	// Stale generated by reconciliation uses ReceivedAt-based staleness; it
	// must not be rejected by event-time ordering (OccurredAt zero).
	out, err = Apply(f, Observation{EpisodeKey: "e1", Signal: SignalStale, ReceivedAt: t2})
	if err != nil || !out.Changed || out.Next.State != StateStale {
		t.Fatalf("stale without occurred_at: %+v %v", out, err)
	}
}

// occurred_at 缺失不破坏乱序保护 (PROC-005): a transition WITHOUT occurred_at
// keeps the previous LastTransitionAt; the next older event is still caught.
func TestMissingOccurredAtDoesNotDisableOrdering(t *testing.T) {
	f := firing("e1", t1)
	out, err := Apply(f, Observation{EpisodeKey: "e1", Signal: SignalStale, ReceivedAt: t2}) // no occurred_at
	if err != nil || !out.Changed {
		t.Fatalf("stale transition: %+v %v", out, err)
	}
	if !out.Next.LastTransitionAt.Equal(t1) {
		t.Fatalf("missing occurred_at wiped LastTransitionAt: %v", out.Next.LastTransitionAt)
	}
	// An older firing must STILL be out-of-order/rejected, proving protection.
	if _, err := Apply(out.Next, obs("e1", SignalResolved, t0)); err != ErrOutOfOrder {
		t.Fatalf("older resolved after zero-occurred transition: err=%v, want ErrOutOfOrder", err)
	}
}

// Stale is terminal-safe: stale on resolved is closed, stale on stale repeats.
func TestStaleEdgeCases(t *testing.T) {
	closed := Snapshot{EpisodeKey: "e1", State: StateResolved, LastObservedAt: t1, LastTransitionAt: t1, Version: 2}
	if _, err := Apply(closed, obs("e1", SignalStale, t2)); err != ErrEpisodeClosed {
		t.Fatalf("stale on resolved: err=%v, want ErrEpisodeClosed", err)
	}
	stale := Snapshot{EpisodeKey: "e1", State: StateStale, LastObservedAt: t1, LastTransitionAt: t1, Version: 2}
	if out, err := Apply(stale, obs("e1", SignalStale, t2)); err != nil || out.Changed {
		t.Fatalf("repeat stale: %+v %v", out, err)
	}
}
