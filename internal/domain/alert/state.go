// Package alert contains a standard-library-only REFERENCE state machine.
// Production correctness also requires DB transaction, version checks and idempotency.
package alert

import (
	"errors"
	"time"
)

type State string
type Signal string

const (
	StatePending  State = "pending"
	StateFiring   State = "firing"
	StateResolved State = "resolved"
	StateStale    State = "stale"

	SignalFiring   Signal = "firing"
	SignalResolved Signal = "resolved"
	SignalStale    Signal = "stale" // generated by source-health reconciliation
)

var (
	ErrInvalidSignal   = errors.New("invalid alert signal")
	ErrNoActiveEpisode = errors.New("cannot resolve or stale an absent alert episode")
	ErrEpisodeClosed   = errors.New("closed episode cannot reopen; create a new episode")
	ErrEpisodeMismatch = errors.New("event episode key does not match active instance")
	ErrOutOfOrder      = errors.New("event older than latest state transition")
)

// Snapshot is one logical (fingerprint, episode) aggregate.
type Snapshot struct {
	EpisodeKey       string
	State            State
	LastObservedAt   time.Time
	LastTransitionAt time.Time
	Version          uint64
}

type Observation struct {
	EpisodeKey string
	Signal     Signal
	OccurredAt time.Time
	ReceivedAt time.Time
}

type Outcome struct {
	Next    Snapshot
	Changed bool
	Reason  string
}

// Apply performs a pure state transition. Empty snapshot represents a new aggregate.
// A duplicate firing updates LastObservedAt without generating a new transition.
func Apply(current Snapshot, o Observation) (Outcome, error) {
	if o.EpisodeKey == "" || o.ReceivedAt.IsZero() {
		return Outcome{}, ErrInvalidSignal
	}
	if current.EpisodeKey != "" && current.EpisodeKey != o.EpisodeKey {
		return Outcome{}, ErrEpisodeMismatch
	}
	if o.Signal != SignalFiring && o.Signal != SignalResolved && o.Signal != SignalStale {
		return Outcome{}, ErrInvalidSignal
	}
	if current.State == "" {
		if o.Signal != SignalFiring {
			return Outcome{}, ErrNoActiveEpisode
		}
		// Missing occurred_at leaves LastTransitionAt zero ("unknown");
		// out-of-order protection stays disabled until a sourced timestamp arrives.
		return Outcome{Next: Snapshot{
			EpisodeKey: o.EpisodeKey, State: StateFiring,
			LastObservedAt: o.ReceivedAt, LastTransitionAt: o.OccurredAt, Version: 1,
		}, Changed: true, Reason: "initial-firing"}, nil
	}
	next := current
	if o.ReceivedAt.After(next.LastObservedAt) {
		next.LastObservedAt = o.ReceivedAt
	}
	// Older *different* state changes must not override an authoritative newer
	// transition. (Stale markings never overwrite LastTransitionAt — see the
	// store's reconcile: the anchor stays SOURCE-authored, so re-confirmation
	// after reconciliation is never misjudged as out-of-order.)
	if !o.OccurredAt.IsZero() && !next.LastTransitionAt.IsZero() && o.OccurredAt.Before(next.LastTransitionAt) {
		if (o.Signal == SignalFiring && current.State == StateFiring) ||
			(o.Signal == SignalResolved && current.State == StateResolved) {
			return Outcome{Next: next, Changed: false, Reason: "duplicate-older-observation"}, nil
		}
		return Outcome{}, ErrOutOfOrder
	}
	switch o.Signal {
	case SignalFiring:
		if current.State == StateResolved {
			return Outcome{}, ErrEpisodeClosed
		}
		if current.State == StateFiring {
			return Outcome{Next: next, Changed: false, Reason: "repeat-firing"}, nil
		}
		next.State = StateFiring
	case SignalResolved:
		if current.State == StateResolved {
			return Outcome{Next: next, Changed: false, Reason: "repeat-resolved"}, nil
		}
		next.State = StateResolved
	case SignalStale:
		if current.State == StateResolved {
			return Outcome{}, ErrEpisodeClosed
		}
		if current.State == StateStale {
			return Outcome{Next: next, Changed: false, Reason: "repeat-stale"}, nil
		}
		next.State = StateStale
	}
	// A missing occurred_at must never wipe the last known transition time:
	// doing so would disable out-of-order protection for all later events.
	if !o.OccurredAt.IsZero() {
		next.LastTransitionAt = o.OccurredAt
	}
	next.Version++
	return Outcome{Next: next, Changed: true, Reason: "state-transition"}, nil
}
