#!/usr/bin/env python3
"""Merge per-service hz router files into one routes.go (single Register).

hz update emits one <service>.go per IDL, each declaring `func Register` in
the same Go package — which does not compile. Running hz once per service
IDL sequentially (so middleware.go accumulates all middleware hooks) and then
merging the Register bodies here keeps a single, generated entry point.

Usage: merge_hz_routers.py <router_pkg_dir> <service_name>...
  <service_name> matches the hz router file stem (proto file basename).
"""
import re
import sys
from pathlib import Path

def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__, file=sys.stderr)
        return 2
    pkg_dir = Path(sys.argv[1])
    services = sys.argv[2:]

    funcs, calls = [], []
    for svc in services:
        src = pkg_dir / f"{svc}.go"
        text = src.read_text(encoding="utf-8")
        m = re.search(
            r"func Register\(r \*server\.Hertz\) \{\n(.*?)\n\}\n?\Z", text, re.S
        )
        if not m:
            print(f"{src}: no Register body found; leaving file as-is", file=sys.Stderr)
            return 1
        body = m.group(1)
        # hz emits "{param}" path segments; this Hertz version registers them
        # as LITERALS (probe test catches any regression), so normalize every
        # path segment to the native ":param" form.
        body = re.sub(r'"/([^"]*)\{(\w+)\}', lambda mm: f'"/{mm.group(1)}:{mm.group(2)}', body)
        body = body.replace('"/{', '"/:')  # group(path) at segment start
        name = "register" + svc.capitalize()
        funcs.append(f"func {name}(r *server.Hertz) {{\n{body}\n}}")
        calls.append(f"\t{name}(r)")
        src.unlink()

    out = pkg_dir / "routes.go"
    out.write_text(
        "// Code generated by scripts/merge_hz_routers.py from hz output. DO NOT EDIT.\n"
        "// Regenerate with: make idl-hz\n"
        "package v1\n\n"
        "import (\n"
        '\t"github.com/cloudwego/hertz/pkg/app/server"\n'
        '\tv1 "github.com/example/alert-platform/internal/adapter/inbound/http/v1"\n'
        ")\n\n"
        "// Register registers every IDL service's routes (single entry point\n"
        "// kept by scripts/merge_hz_routers.py; middleware hooks live in middleware.go).\n"
        "func Register(r *server.Hertz) {\n"
        + "\n".join(calls)
        + "\n}\n\n"
        + "\n\n".join(funcs)
        + "\n",
        encoding="utf-8",
    )
    print(f"OK: merged {len(services)} service routers into {out}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
